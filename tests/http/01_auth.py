import sys; import os; sys.path.insert(0,os.path.dirname(os.path.abspath(__file__)))
from httpkit import *
b=B()
b.get('/login'); check('login page loads',b.r.status_code==200 and 'Welcome back' in b.last)
check('setup link shown when no users','Create the first administrator' in b.last)
r=b.get('/app/dashboard'); check('protected page redirects anon to login','/login' in b.r.url and 'Welcome back' in b.last)
# CSRF: POST without token is rejected
r=requests.post(BASE+'/login',data={'username':'x','password':'y'},allow_redirects=True); check('POST without CSRF token rejected',('expired' in r.url) or ('session has expired' in r.text))
# first-run setup
b.get('/setup'); check('setup page loads','First-run setup' in b.last)
b.post('/setup',{'fullName':'Test Admin','username':'admin_test','email':'admin@example.org','phone':'','password':'weak','confirmPassword':'weak'})
check('weak password rejected',b.alert() and b.alert()[0]=='danger',b.alert())
b.post('/setup',{'fullName':'Test Admin','username':'admin_test','email':'admin@example.org','phone':'','password':'Sup3rSecret99','confirmPassword':'Sup3rSecret99'})
check('admin created -> login with success banner','Administrator created' in b.last,b.alert())
b.get('/setup'); check('setup is 404 once a user exists',b.r.status_code==404)
b.post('/login',{'username':'admin_test','password':'wrong'}); check('bad password rejected',b.alert() and b.alert()[0]=='danger',b.alert())
b.post('/login',{'username':'admin_test','password':'Sup3rSecret99'}); check('login succeeds -> dashboard',b.r.url.endswith('/app/dashboard') and 'Dashboard' in b.last,b.r.url)
check('sidebar shows ResQHub branding','Help. Hope. Humanity.' in b.last)
check('user menu shows admin','Test Admin' in b.last)
check('security headers set','default-src' in b.r.headers.get('Content-Security-Policy','') and b.r.headers.get('X-Frame-Options')=='DENY')
b.get('/app/profile'); check('profile page',('Change password' in b.last))
b.post('/logout'); check('logout -> login page','Welcome back' in b.last)
b.get('/app/dashboard'); check('after logout dashboard blocked','Welcome back' in b.last)
sys.exit(1 if summary() else 0)
